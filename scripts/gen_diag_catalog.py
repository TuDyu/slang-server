#!/usr/bin/env python3
"""
gen_diag_catalog.py
Generate a C++ table of slang's configurable warnings from diagnostics.txt.

slang can emit diagnostics, but it does not expose the -W option names, warning
groups, or human readable descriptions that a configuration UI needs. Those live
only in scripts/diagnostics.txt, so we parse that file at build time and emit a
plain data table.

SPDX-FileCopyrightText: Hudson River Trading
SPDX-License-Identifier: MIT
"""

import argparse
import shlex
from collections import defaultdict
from pathlib import Path

HEADER = """//------------------------------------------------------------------------------
// DiagCatalog.inc
// Generated by scripts/gen_diag_catalog.py from slang's diagnostics.txt.
// Do not edit by hand.
//------------------------------------------------------------------------------
"""


def escape_cpp(text: str) -> str:
    """Escape text for inclusion in a C++ string literal."""
    return text.replace("\\", "\\\\").replace('"', '\\"')


def parse(text: str):
    """Return (entries, group_members).

    entries: warning option name, C++ name, subsystem and description
    group_members: warning option name -> list of group names
    """
    entries = []
    diag_groups = defaultdict(list)
    subsystem = "General"
    pending_group = None

    def add_members(group_name, tokens):
        for token in tokens:
            if group_name not in diag_groups[token]:
                diag_groups[token].append(group_name)

    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("//"):
            continue

        if pending_group is not None:
            tokens = line.split()
            closed = bool(tokens) and tokens[-1] == "}"
            if closed:
                tokens = tokens[:-1]
            add_members(pending_group, tokens)
            if closed:
                pending_group = None
            continue

        parts = shlex.split(line)
        if not parts:
            continue

        if parts[0] == "subsystem":
            subsystem = parts[1]
        elif parts[0] == "group":
            group_name = parts[1]
            members = parts[4:] if len(parts) > 4 else []
            closed = bool(members) and members[-1] == "}"
            if closed:
                members = members[:-1]
            add_members(group_name, members)
            if not closed:
                pending_group = group_name
        elif parts[0] == "warning" and len(parts) >= 4:
            entries.append(
                {
                    "option": parts[1],
                    "name": parts[2],
                    "subsystem": subsystem,
                    "description": parts[3],
                }
            )

    return entries, diag_groups


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, help="path to slang's diagnostics.txt")
    parser.add_argument("--output", required=True, help="path of the generated .inc file")
    args = parser.parse_args()

    entries, groups = parse(Path(args.input).read_text(encoding="utf-8"))

    out = [HEADER]
    for entry in entries:
        members = ",".join(groups.get(entry["option"], []))
        out.append(
            "\t{"
            f'"{escape_cpp(entry["option"])}", '
            f'"{escape_cpp(entry["name"])}", '
            f'"{escape_cpp(entry["subsystem"])}", '
            f'"{escape_cpp(entry["description"])}", '
            f'"{escape_cpp(members)}"'
            "},\n"
        )

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(out), encoding="utf-8")
    print(f"Generated {len(entries)} diagnostic entries in {output}")


if __name__ == "__main__":
    main()
